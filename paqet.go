package main

// Paqet (https://github.com/hanselime/paqet) is a raw-packet proxy: it
// crafts and captures TCP packets directly with pcap, bypassing the host's
// own TCP/IP stack and connection tracking, and carries KCP+smux on top for
// a fast, reliable, encrypted, multiplexed transport. That's a genuinely
// different engine from rmtunnel's own protocol.go — not something to
// reimplement here, so this wraps the real paqet binary instead: download
// it, generate its own YAML config from a guided wizard, and manage it as
// its own systemd service, alongside rmtunnel's native tunnels in the same
// "Manage tunnels" screen.
//
// paqet's own role naming doesn't match rmtunnel's Role: paqet's "client"
// is the side with socks5/forward — i.e. the box exposing ports to real
// users — and it's also the side that dials out first. paqet's "server" is
// the side being dialed, which is also where the real backend lives. So a
// paqet tunnel is inherently shaped like rmtunnel's Direction "direct": the
// ports-owning side initiates. See docs on Direction in config.go.

import (
	"fmt"
	"os"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	paqetRepoOwner = "hanselime"
	paqetRepoName  = "paqet"
	paqetBinPath   = "/usr/local/bin/paqet"
)

// --- config schema (mirrors paqet's own YAML — see conf.go in its source) -

type paqetLog struct {
	Level string `yaml:"level"`
}

type paqetListen struct {
	Addr string `yaml:"addr"`
}

type paqetSocks5 struct {
	Listen   string `yaml:"listen"`
	Username string `yaml:"username,omitempty"`
	Password string `yaml:"password,omitempty"`
}

type paqetForward struct {
	Listen   string `yaml:"listen"`
	Target   string `yaml:"target"`
	Protocol string `yaml:"protocol"`
}

type paqetAddr struct {
	Addr      string `yaml:"addr"`
	RouterMAC string `yaml:"router_mac"`
}

type paqetTCP struct {
	LocalFlag  []string `yaml:"local_flag,omitempty"`
	RemoteFlag []string `yaml:"remote_flag,omitempty"`
}

type paqetPCAP struct {
	Sockbuf int `yaml:"sockbuf,omitempty"`
}

type paqetNetwork struct {
	Interface string     `yaml:"interface"`
	GUID      string     `yaml:"guid,omitempty"`
	IPv4      paqetAddr  `yaml:"ipv4"`
	TCP       paqetTCP   `yaml:"tcp"`
	PCAP      *paqetPCAP `yaml:"pcap,omitempty"`
}

type paqetServerAddr struct {
	Addr string `yaml:"addr"`
}

// paqetKCP mirrors paqet's transport.kcp block. NoDelay/Interval/Resend/
// NoCongestion/WDelay/AckNoDelay are pointers so they're only emitted for
// mode "manual" — paqet derives them from named presets (normal/fast/
// fast2/fast3) internally otherwise, and 0/false are meaningful values that
// omitempty on a plain int/bool would wrongly drop.
type paqetKCP struct {
	Mode         string `yaml:"mode"`
	NoDelay      *int   `yaml:"nodelay,omitempty"`
	Interval     *int   `yaml:"interval,omitempty"`
	Resend       *int   `yaml:"resend,omitempty"`
	NoCongestion *int   `yaml:"nocongestion,omitempty"`
	WDelay       *bool  `yaml:"wdelay,omitempty"`
	AckNoDelay   *bool  `yaml:"acknodelay,omitempty"`

	MTU    int `yaml:"mtu,omitempty"`
	Rcvwnd int `yaml:"rcvwnd,omitempty"`
	Sndwnd int `yaml:"sndwnd,omitempty"`
	Dshard int `yaml:"dshard,omitempty"` // FEC data shards, 0 = FEC disabled
	Pshard int `yaml:"pshard,omitempty"` // FEC parity shards

	Block string `yaml:"block,omitempty"`
	Key   string `yaml:"key"`

	Smuxbuf      int `yaml:"smuxbuf,omitempty"`
	Streambuf    int `yaml:"streambuf,omitempty"`
	Smuxkalive   int `yaml:"smuxkalive,omitempty"`
	Smuxktimeout int `yaml:"smuxktimeout,omitempty"`
}

type paqetTransport struct {
	Protocol string   `yaml:"protocol"`
	Conn     int      `yaml:"conn"`
	KCP      paqetKCP `yaml:"kcp"`
}

type paqetConf struct {
	Role      string           `yaml:"role"`
	Log       paqetLog         `yaml:"log"`
	Listen    *paqetListen     `yaml:"listen,omitempty"`
	SOCKS5    []paqetSocks5    `yaml:"socks5,omitempty"`
	Forward   []paqetForward   `yaml:"forward,omitempty"`
	Network   paqetNetwork     `yaml:"network"`
	Server    *paqetServerAddr `yaml:"server,omitempty"`
	Transport paqetTransport   `yaml:"transport"`
}

func renderPaqetYAML(c *paqetConf) (string, error) {
	data, err := yaml.Marshal(c)
	if err != nil {
		return "", err
	}
	return "# generated by the rmtunnel wizard for paqet — https://github.com/hanselime/paqet\n" + string(data), nil
}

func loadPaqetConf(path string) (*paqetConf, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var c paqetConf
	if err := yaml.Unmarshal(data, &c); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}
	return &c, nil
}

