// --- TCP flag helpers ---------------------------------------------------

// paqetTCPFlagChoices mirrors network.tcp.local_flag/remote_flag — cycling
// through more than one pattern varies the traffic's shape; a single entry
// is the common case.
var paqetTCPFlagChoices = []string{"PA", "S", "A", "SA", "F", "R"}

func parsePaqetFlags(raw string) []string {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return []string{"PA"}
	}
	var out []string
	for _, p := range strings.Split(raw, ",") {
		if p = strings.ToUpper(strings.TrimSpace(p)); p != "" {
			out = append(out, p)
		}
	}
	if len(out) == 0 {
		return []string{"PA"}
	}
	return out
}

// --- misc helpers --------------------------------------------------------

func parseIntDefault(s string, def int) int {
	v, err := strconv.Atoi(strings.TrimSpace(s))
	if err != nil {
		return def
	}
	return v
}
